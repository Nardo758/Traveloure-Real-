#!/usr/bin/env node
/**
 * LW-1f (ledger `2026-10-16-lw1f-kyoto-ticker`; LW-1 Phase 0 answer 3, "committed client route list plus CI
 * staleness test: approved"): writes `shared/client-routes.generated.ts`, the list of every `<Route path="...">`
 * in `client/src/App.tsx`, so the SERVER can tell a real client page from a dead link when an admin saves a ticker
 * line (shared/ticker.ts `isClientRoutePath`).
 *
 *   node scripts/generate-client-routes.cjs           # regenerate
 *   node scripts/generate-client-routes.cjs --check   # CI: exit 1 when the committed file is stale
 *
 * NEGATIVE SPACE (§18d): it reads literal `path="..."` attributes in App.tsx and nothing else. A route declared
 * with a computed path, in another file, or behind a nested router is not listed — and so a ticker link to it is
 * refused at save (fail closed, never a dead link). It does not prove the page renders, only that a route exists.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const APP = path.join(ROOT, "client/src/App.tsx");
const OUT = path.join(ROOT, "shared/client-routes.generated.ts");

function extractRoutes(source) {
  const seen = new Set();
  for (const m of source.matchAll(/<Route\b[^>]*?\bpath="([^"]+)"/g)) seen.add(m[1]);
  return [...seen].sort();
}

function render(routes) {
  return [
    "// GENERATED by scripts/generate-client-routes.cjs from client/src/App.tsx — do not edit by hand.",
    "// Regenerate with `node scripts/generate-client-routes.cjs`; CI fails when this file is stale.",
    "export const CLIENT_ROUTES: readonly string[] = [",
    ...routes.map((r) => `  ${JSON.stringify(r)},`),
    "];",
    "",
  ].join("\n");
}

const expected = render(extractRoutes(fs.readFileSync(APP, "utf8")));
if (process.argv.includes("--check")) {
  const actual = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (actual !== expected) {
    console.error("shared/client-routes.generated.ts is stale. Run: node scripts/generate-client-routes.cjs");
    process.exit(1);
  }
  console.log(`client route list current (${extractRoutes(fs.readFileSync(APP, "utf8")).length} routes).`);
} else {
  fs.writeFileSync(OUT, expected);
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}
