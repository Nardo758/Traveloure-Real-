import { chromium } from "@playwright/test";
import fs from "node:fs";
const BASE = process.env.BASE_URL || "http://127.0.0.1:5000";
const dir = "docs/audits/ui/chat__first-message";
const b = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
const c = await b.newContext({ viewport: { width: 1360, height: 900 } });
const p = await c.newPage();
const net = [];
p.on("response", async (r) => { const q = r.request(); if (q.url().includes("/api/") && q.method() !== "GET") { let t = ""; try { t = (await r.text()).slice(0, 300); } catch {} net.push({ method: q.method(), url: q.url().replace(BASE, ""), status: r.status(), body: (q.postData() || "").slice(0, 300), response: t }); } });
const email = `u2c-${Date.now()}@traveloure.test`;
await c.request.post(`${BASE}/api/auth/register`, { data: { email, password: "TestPassword123!", firstName: "U2c", lastName: "Chat", userType: "user" } });
await c.request.post(`${BASE}/api/auth/accept-terms`, { data: { acceptTerms: true, acceptPrivacy: true } });
await p.goto(`${BASE}/s/kansai-bizlang`, { waitUntil: "domcontentloaded" });
await p.waitForTimeout(2000);
await p.screenshot({ path: `${dir}/before.png` });
await p.getByTestId("button-message-storefront").click();
await p.waitForTimeout(3000);
await p.getByTestId("input-message").fill("Hello, is the Kyoto interpreter available in November?");
await p.screenshot({ path: `${dir}/composed.png` });
await p.getByTestId("button-send").click();
await p.waitForTimeout(2500);
const toasts = (await p.locator('li[data-state="open"], [role="status"]').allInnerTexts().catch(() => [])).map((t) => t.replace(/\s+/g, " "));
await p.screenshot({ path: `${dir}/after.png` });
const inputVal = await p.getByTestId("input-message").inputValue().catch(() => null);
fs.writeFileSync(`${dir}/network.json`, JSON.stringify(net, null, 1));
fs.writeFileSync(`${dir}/result.json`, JSON.stringify({ rowId: "chat:send-message#first-message", url: p.url().replace(BASE, ""), toasts, inputAfterSend: inputVal }, null, 1));
console.log(JSON.stringify({ url: p.url().replace(BASE, ""), toasts, inputAfterSend: inputVal, net: net.filter((x) => /chats|conversations/.test(x.url)) }, null, 1));
await b.close();
