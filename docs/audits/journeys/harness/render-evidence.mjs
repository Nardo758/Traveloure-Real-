// Renders docs/audits/journeys/<J>/EVIDENCE.md from the per-run record.json files.
import fs from "node:fs";
import path from "node:path";
const J = process.argv[2] || "J1";
const root = path.resolve("docs/audits/journeys", J);
const NOISE = /moments\/event|analytics|impression|track|cross-sell|upsell|geocode|cities\/|grok|travelpulse|tourist|weather|notifications|auth\/user|me\/|pricing|feature|landing|conversations|messages|categories|experience-types|markets|build-info|ready/;
const short = (s, n) => (s || "").replace(/\|/g, "\\|").replace(/\s+/g, " ").slice(0, n);
let md = `# ${J} — per-step evidence (generated)\n\nGenerated by \`docs/audits/journeys/harness/render-evidence.mjs\` from each run's \`record.json\`. **Network** lists /api calls that write, plus trip/cart/context reads; analytics and chrome reads are omitted (the full log is in record.json). **DB** is the row diff of trips / itinerary_items / cart_items / user_experiences / trip_contexts / trip_destinations taken after the step.\n`;
for (const dir of fs.readdirSync(root).filter((d) => fs.existsSync(path.join(root, d, "record.json"))).sort()) {
  const r = JSON.parse(fs.readFileSync(path.join(root, dir, "record.json"), "utf8"));
  md += `\n## ${dir}\n\nauth=${r.auth} · branch=${r.branch}${r.aiAction ? ` (${r.aiAction})` : ""} · precache=${r.precache} · user=${r.user?.id ?? "guest"}\n\n| k | step | url | network | DB diff | screenshot |\n|---|---|---|---|---|---|\n`;
  for (const s of r.steps) {
    const net = s.network
      .filter((n) => !NOISE.test(n.url) && (n.method !== "GET" || /\/api\/(trips|cart|trip-context)/.test(n.url)))
      .filter((n) => !/\/(plancard|suggestions|trip-pass|guests|expert-advisor|proposals)$/.test(n.url))
      .map((n) => `\`${n.method} ${short(n.url.split("?")[0], 70)}\` → ${n.status}`)
      .join("<br>");
    const db = Object.entries(s.dbDiff)
      .map(([t, d]) => `${t}: +${d.added.length}${d.removed.length ? ` −${d.removed.length}` : ""}${d.changed.length ? ` ~${d.changed.length}` : ""}` +
        (d.added.length ? ` (${d.added.map((x) => ["trip_id", "user_id", "guest_session_id"].filter((c) => c in x).map((c) => `${c}=${x[c] ? String(x[c]).slice(0, 8) : "NULL"}`).join(",")).join("; ")})` : ""))
      .join("<br>");
    md += `| ${s.step} | ${short(s.label, 70)}${s.note ? ` — _${short(s.note, 60)}_` : ""} | \`${short(s.url.split("?")[0], 30)}\` | ${net || "—"} | ${db || "—"} | [png](${s.screenshot.replace(dir + "/", dir + "/")}) |\n`;
  }
}
fs.writeFileSync(path.join(root, "EVIDENCE.md"), md);
console.log("wrote", path.join(root, "EVIDENCE.md"));
