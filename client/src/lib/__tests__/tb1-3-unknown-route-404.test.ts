/**
 * TB1.3 — an unknown URL answers 404 and still renders the SPA's not-found page.
 *
 * The list of known routes is GENERATED from `App.tsx` (never hand-written), and it understands
 * `:param` segments — which is the whole safety story: a legitimate deep link keeps its 200 and only
 * a dead path becomes a 404.
 *
 *   N1 a known STATIC route is a page
 *   N2 a DYNAMIC route with a valid param is a page
 *   N3 a bogus path is NOT a page
 *   N4 the manifest is the generated one, and it lists the dynamic routes verbatim
 *   N5 the server asks that predicate, for HTML GETs only, and never swallows /api or an asset
 *
 * Run: npx tsx --test client/src/lib/__tests__/tb1-3-unknown-route-404.test.ts
 */
import { describe, it } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import { isClientRoutePath } from "@shared/ticker";
import { CLIENT_ROUTES } from "@shared/client-routes.generated";

const SEO = fs.readFileSync("server/routes/seo.routes.ts", "utf8");
const GENERATED = fs.readFileSync("shared/client-routes.generated.ts", "utf8");

describe("TB1.3 — the route predicate", () => {
  it("N1 a known static route is a page", () => {
    for (const route of ["/", "/terms", "/privacy", "/careers", "/discover", "/experiences"]) {
      assert.equal(isClientRoutePath(route), true, `${route} is a page`);
    }
  });

  it("N2 a dynamic route with a valid param is a page", () => {
    for (const path of ["/plans/abc123", "/trip/abc123", "/services/some-id", "/blog/hello-world"]) {
      assert.equal(isClientRoutePath(path), true, `${path} is a page`);
    }
    // …and a param segment must be non-empty: `/plans/` is not `/plans/:id`.
    assert.equal(isClientRoutePath("/plans/"), isClientRoutePath("/plans"), "a trailing slash never invents a param");
  });

  it("N3 a bogus path is not a page", () => {
    for (const path of ["/nosuchpage", "/definitely/not/a/route", "/terms/extra/segments"]) {
      assert.equal(isClientRoutePath(path), false, `${path} is not a page`);
    }
  });
});

describe("TB1.3 — the manifest is generated, and the server uses it", () => {
  it("N4 the committed manifest is the generator's output", () => {
    assert.match(GENERATED, /GENERATED by scripts\/generate-client-routes\.cjs/, "a generated file, never hand-written");
    assert.match(GENERATED, /export const CLIENT_ROUTES: readonly string\[\] = \[/);
    for (const dynamic of ["/plans/:tripId", "/trip/:id", "/services/:id", "/blog/:slug"]) {
      assert.ok(GENERATED.includes(`"${dynamic}"`), `${dynamic} is in the manifest`);
    }
    assert.ok(CLIENT_ROUTES.length > 100, "it is the whole app, not a sample");
  });

  it("N5 the server asks that predicate — HTML GETs only, and never /api or an asset", () => {
    assert.match(SEO, /import \{ isClientRoutePath \} from "@shared\/ticker";/);
    assert.match(SEO, /if \(isClientRoutePath\(req\.path\)\) return next\(\);/, "a known page keeps its 200");
    assert.match(SEO, /if \(req\.method !== "GET" && req\.method !== "HEAD"\) return next\(\);/);
    assert.match(SEO, /if \(!req\.accepts\("html"\)\) return next\(\);/, "a JSON client is not served a page");
    assert.match(SEO, /NOT_A_PAGE_PATH = \/\^\\\/\(api\|assets\|images\|attachments\|uploads\|static\|/, "api and assets are excluded");
    assert.match(SEO, /return res\.status\(404\)\.set\(\{ "Content-Type": "text\/html" \}\)\.end\(template\);/, "a real 404 with the SPA shell");
  });
});

describe("TB1.3 — the dev server's own modules are never pages", () => {
  it("N6 Vite's module requests and file-looking paths fall through, and a bogus page still 404s", () => {
    // The e2e gates run `npm run dev`, and the first cut answered `/@vite/client` with the 404 shell,
    // so the app never booted and every spec failed on a blank page. Both guards now exist.
    assert.match(SEO, /NOT_A_PAGE_PATH = \/\^\\\/\(api\|assets\|images\|attachments\|uploads\|static\|@[^/]+\|src\|node_modules/);
    assert.match(SEO, /const LOOKS_LIKE_A_FILE = \/\\\.[a-z0-9]{1,16}\$\/i;/);
    assert.match(SEO, /if \(LOOKS_LIKE_A_FILE\.test\(req\.path\)\) return next\(\);/);

    // The predicates themselves, replayed over the paths that matter.
    const notAPage = /^\/(api|assets|images|attachments|uploads|static|@[^/]+|src|node_modules|\.vite|og-cover\.png|sitemap\.xml|robots\.txt)(\/|$)/;
    const looksLikeAFile = /\.[a-z0-9]{1,10}$/i;
    const isDevModule = (p: string) => notAPage.test(p) || looksLikeAFile.test(p);
    for (const devPath of ["/@vite/client", "/@react-refresh", "/src/main.tsx", "/src/App.tsx", "/node_modules/.vite/deps/react.js", "/favicon.ico", "/manifest.webmanifest", "/og-cover.png", "/sitemap.xml", "/robots.txt"]) {
      assert.equal(isDevModule(devPath), true, `${devPath} must never be answered with the 404 shell`);
    }
    for (const pagePath of ["/nosuchpage", "/definitely/not/a/route", "/terms/extra"]) {
      assert.equal(isDevModule(pagePath), false, `${pagePath} is still judged by the route table`);
      assert.equal(isClientRoutePath(pagePath), false, `${pagePath} is not a page`);
    }
  });
});