/**
 * F5 (UI batch 1): every Ask button reads "Ask an expert" (Leon, Nov 19, ruling 2).
 *
 * "Ask a local", "Ask a trip planner" and "Ask an event planner" are approved ONLY as options inside the
 * chooser or the door. The words live in `ask-expert-copy.ts`; the button is `AskExpertButton`. No other
 * traveler file authors an Ask label of its own.
 *
 * The plan pages are OUT of this slice: their "Ask a local about this" entries are replaced by the one door
 * (UI brief 19), not by the chooser (ruling 3). They are named below with that reason; the list only shrinks.
 *
 * WRITTEN BEFORE THE BUILD. Do not edit this file to make it pass; if a case is wrong, stop and write it up.
 *
 * Run: npx tsx --test client/src/lib/__tests__/f5-one-ask-label.test.ts
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { ASK_EXPERT_COPY } from "../ask-expert-copy";

const ROOT = resolve(import.meta.dirname, "../../../..");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");
const code = (src: string) => src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "").replace(/\{\/\*[\s\S]*?\*\/\}/g, "");
function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(resolve(ROOT, dir))) {
    const rel = `${dir}/${name}`;
    if (statSync(resolve(ROOT, rel)).isDirectory()) {
      if (name !== "__tests__" && name !== "node_modules") walk(rel, out);
    } else if (/\.tsx?$/.test(name)) out.push(rel.split(/[\\/]/).join("/"));
  }
  return out;
}

/** An Ask label written into a file: a quoted or JSX-text "Ask ..." phrase, or a templated "Ask {name}". */
const ASK_LABEL = /(["'`>]\s*)Ask (an expert|a local|the local|this expert|a trip planner|an event planner|\$\{|\{)/;

const NAMED: Record<string, string> = {
  "client/src/lib/ask-expert-copy.ts": "the approved words, the one place they live",
  "client/src/components/plan/ItemSheet.tsx": "plan page: replaced by the one door (UI brief 19), ruling 3",
};

test("F5.1 no traveler file authors an Ask label of its own", () => {
  const offenders: string[] = [];
  for (const file of walk("client/src")) {
    if (NAMED[file]) continue;
    if (ASK_LABEL.test(code(read(file)))) offenders.push(file);
  }
  assert.deepEqual(offenders, [], "an Ask label drawn outside ask-expert-copy.ts");
});

test("F5.2 a named file that no longer needs naming is removed from the list", () => {
  for (const file of Object.keys(NAMED)) {
    let src: string;
    try {
      src = read(file);
    } catch {
      continue; // deleted: nothing to be stale about
    }
    assert.ok(ASK_LABEL.test(code(src)), `${file} no longer needs naming - remove it`);
  }
});

test("F5.3 the retired label keys are gone, and the button reads the approved word", () => {
  assert.equal(ASK_EXPERT_COPY.button, "Ask an expert");
  const tile = read("client/src/lib/tile-action-copy.ts");
  assert.doesNotMatch(tile, /askThisExpert|Ask this expert/, "tile-action-copy carries no Ask wording of its own");
  const blog = code(read("client/src/pages/blog-post.tsx"));
  assert.doesNotMatch(blog, /Ask the local/, "the blog byline's button reads the one label");
  assert.match(blog, /\{ASK_EXPERT_COPY\.button\}/, "from the approved copy");
  assert.match(blog, /startConversation\(\{ blogPostSlug: post\.slug \}\)/, "and stays addressed to the post's author: no chooser");
});
